// Rebuild only the todos deployment entry from its tested shared module.
// Does not deploy, authenticate, or change entities.
//
// Why: a published function that imports a shared .mjs module does not load
// (job-knowledge and research-queue were changed to single-file bundles for the
// same reason). todoService.mjs has no imports, so the bundle is a plain
// concatenation: SDK import + the tested module (export keyword removed) + entry.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = path => fs.readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n');

export const TODOS_ENTRY_HEADER = `// Generated by scripts/build-todos-entry.mjs from base44/shared/todoService.mjs
// (tested by tests/todoService.test.mjs). Edit that module and rebuild; do not edit by hand.
import { createClientFromRequest } from 'npm:@base44/sdk@0.8.48';
`;

export const TODOS_ENTRY_TAIL = `
// Owner check mirrors src/lib/agentCenterAccess.js (isAgentCenterOwner).
// Gabriel's two sign-ins are the only owner accounts: team views, assigning
// tasks to others, and member management. Everyone else sees only their own list.
const OWNER_EMAILS = new Set(["gabefronk@gmail.com", "gabriel.fronk.wd@gmail.com"]);
const isOwner = (user) => user?.role === "admin" && OWNER_EMAILS.has(String(user?.email || "").trim().toLowerCase());

Deno.serve(createTodoHandler({ getClient: async (req) => createClientFromRequest(req), isOwner }));
`;

export function buildTodosEntry() {
  const service = read('base44/shared/todoService.mjs');
  if (/^\s*import\s/m.test(service) || (service.match(/^export /gm) || []).length !== 1 || !service.includes('export function createTodoHandler(')) {
    throw new Error('todoService.mjs layout changed (imports or extra exports); update this build script.');
  }
  const body = service.replace('export function createTodoHandler(', 'function createTodoHandler(').replace(/\s*$/, '\n');
  return TODOS_ENTRY_HEADER + '\n' + body + TODOS_ENTRY_TAIL;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  fs.writeFileSync(new URL('base44/functions/todos/entry.ts', root), buildTodosEntry());
  console.log('Rebuilt base44/functions/todos/entry.ts from tested shared module; not deployed.');
}
