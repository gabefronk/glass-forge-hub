// Rebuild only the job-documents deployment entry from its tested shared modules.
// Does not deploy, authenticate, or change entities.
//
// Why: a published function that imports a shared .mjs module does not load
// (todos, job-knowledge and research-queue were changed to single-file bundles for
// the same reason). The bundle is a plain concatenation: SDK import +
// jobDocumentsAccess.mjs + jobDocuments.mjs (import lines and export keywords
// removed) + the same Deno.serve wiring the thin wrapper used.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = path => fs.readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n');

export const JOB_DOCUMENTS_ENTRY_HEADER = `// Generated by scripts/build-job-documents-entry.mjs from base44/shared/jobDocumentsAccess.mjs
// and base44/shared/jobDocuments.mjs (tested by tests/jobDocuments.test.mjs).
// Edit those modules and rebuild; do not edit by hand.
import {createClientFromRequest} from 'npm:@base44/sdk@0.8.48';
`;

export const JOB_DOCUMENTS_ENTRY_TAIL = `
Deno.serve(createJobDocumentsHandler({getClient:createClientFromRequest}));
`;

const ACCESS_IMPORT = "import { canReadJobDocuments, canWriteJobDocuments } from './jobDocumentsAccess.mjs';\n";

function stripExports(source, name) {
  if (/^\s*export\s+(default|\{|\*)/m.test(source)) throw new Error(`${name} layout changed (default/re-exports); update this build script.`);
  return source.replace(/^export (const|function|async function) /gm, '$1 ').replace(/\s*$/, '\n');
}

export function buildJobDocumentsEntry() {
  const access = read('base44/shared/jobDocumentsAccess.mjs');
  const docs = read('base44/shared/jobDocuments.mjs');
  if (/^\s*import\s/m.test(access)) throw new Error('jobDocumentsAccess.mjs gained imports; update this build script.');
  const docImports = docs.match(/^\s*import\s.*$/gm) || [];
  if (docImports.length !== 1 || !docs.includes(ACCESS_IMPORT) || !docs.includes('export function createJobDocumentsHandler(')) {
    throw new Error('jobDocuments.mjs layout changed (imports or handler export); update this build script.');
  }
  return JOB_DOCUMENTS_ENTRY_HEADER
    + '\n// base44/shared/jobDocumentsAccess.mjs\n' + stripExports(access, 'jobDocumentsAccess.mjs')
    + '\n// base44/shared/jobDocuments.mjs\n' + stripExports(docs.replace(ACCESS_IMPORT, ''), 'jobDocuments.mjs')
    + JOB_DOCUMENTS_ENTRY_TAIL;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  fs.writeFileSync(new URL('base44/functions/job-documents/entry.ts', root), buildJobDocumentsEntry());
  console.log('Rebuilt base44/functions/job-documents/entry.ts from tested shared modules; not deployed.');
}
